#!/usr/bin/env python3
"""Fail fast when a configured emulator smoke class has no matching test source.

The canonical class list is still generated by android-smoke-tests.sh; this
validator merely checks the registration before any emulator image is installed.
It reads source files only and never opens clinical databases or runs tests.
"""
from __future__ import annotations

import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parent.parent
TEST_ROOTS = (
    ROOT / "Calendula/src/androidTest/java",
    ROOT / "Calendula/src/androidTest/kotlin",
)
CLASS_NAME = re.compile(r"^[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)+$")
PACKAGE = re.compile(r"(?m)^[ \t]*package[ \t]+([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*)[ \t]*;?")
# Java and Kotlin both use 'class'; Kotlin may also use 'object'.
DECLARATION = r"\b(?:class|object)\s+{}\b"


def validate(classes: list[str], roots: tuple[Path, ...]) -> list[str]:
    failures: list[str] = []
    if not classes:
        return ["No Android emulator smoke classes were registered"]

    seen: set[str] = set()
    for fqcn in classes:
        if not CLASS_NAME.fullmatch(fqcn):
            failures.append(f"Malformed instrumentation class: {fqcn!r}")
            continue
        if fqcn in seen:
            failures.append(f"Duplicate instrumentation class: {fqcn}")
            continue
        seen.add(fqcn)

        package, simple_name = fqcn.rsplit(".", 1)
        relative = Path(*fqcn.split("."))
        candidates = [
            root / relative.with_suffix(extension)
            for root in roots
            for extension in (".java", ".kt")
        ]
        source = next((candidate for candidate in candidates if candidate.is_file()), None)
        if source is None:
            failures.append(f"Missing Java/Kotlin test source for {fqcn}")
            continue

        body = source.read_text(encoding="utf-8")
        package_match = PACKAGE.search(body)
        if package_match is None or package_match.group(1) != package:
            failures.append(f"Package mismatch in {source}: expected {package}")
            continue
        if not re.search(DECLARATION.format(re.escape(simple_name)), body):
            failures.append(f"Missing class declaration {simple_name} in {source}")

    return failures


def self_test() -> None:
    # Disposable source tree: no application code or Android runtime required.
    with tempfile.TemporaryDirectory(prefix="calendula-smoke-validator-") as tmp:
        root = Path(tmp)
        source = root / "org/example/ValidSmokeTest.java"
        source.parent.mkdir(parents=True)
        source.write_text("package org.example;\npublic class ValidSmokeTest {}\n", encoding="utf-8")
        assert validate(["org.example.ValidSmokeTest"], (root,)) == []
        assert any("Duplicate" in v for v in validate(
            ["org.example.ValidSmokeTest", "org.example.ValidSmokeTest"], (root,)))
        assert any("Missing Java" in v for v in validate(
            ["org.example.MissingSmokeTest"], (root,)))
        assert any("Malformed" in v for v in validate(["not a class"], (root,)))
        source.write_text("package org.other;\npublic class ValidSmokeTest {}\n", encoding="utf-8")
        assert any("Package mismatch" in v for v in validate(
            ["org.example.ValidSmokeTest"], (root,)))
    print("Android smoke-registration validator self-tests passed")


def main() -> int:
    if len(sys.argv) == 2 and sys.argv[1] == "--self-test":
        self_test()
        return 0
    if len(sys.argv) != 1:
        print("Usage: validate_android_smoke_sources.py [--self-test]", file=sys.stderr)
        return 2

    environment = os.environ.copy()
    environment["CALENDULA_SMOKE_LIST_ONLY"] = "1"
    run = subprocess.run(
        ["bash", "scripts/android-smoke-tests.sh"],
        cwd=ROOT,
        env=environment,
        capture_output=True,
        text=True,
        check=False,
    )
    if run.returncode:
        print(run.stderr or "Could not enumerate smoke tests", file=sys.stderr)
        return run.returncode

    names = [line.strip() for line in run.stdout.splitlines() if line.strip()]
    errors = validate(names, TEST_ROOTS)
    for error in errors:
        print("::error::" + error, file=sys.stderr)
    if errors:
        print(f"Smoke test class validation failed: {len(errors)} error(s)", file=sys.stderr)
        return 1
    print(f"Validated {len(names)} Android emulator smoke classes and source declarations")
    return 0


if __name__ == "__main__":
    sys.exit(main())
