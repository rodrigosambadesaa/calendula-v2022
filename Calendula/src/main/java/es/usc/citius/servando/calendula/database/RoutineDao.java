package es.usc.citius.servando.calendula.database;

import android.content.Context;

import com.j256.ormlite.dao.Dao;
import com.j256.ormlite.stmt.QueryBuilder;
import com.j256.ormlite.stmt.Where;

import org.joda.time.LocalTime;

import java.sql.SQLException;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.Callable;

import es.usc.citius.servando.calendula.CalendulaApp;
import es.usc.citius.servando.calendula.events.PersistenceEvents;
import es.usc.citius.servando.calendula.persistence.Patient;
import es.usc.citius.servando.calendula.persistence.Routine;
import es.usc.citius.servando.calendula.healthcareprovider.persistence.RepeatType;
import es.usc.citius.servando.calendula.util.LogUtil;

public class RoutineDao extends GenericDao<Routine, Long> {

    private static final String TAG = "RoutineDao";

    public RoutineDao(DatabaseHelper db) {
        super(db);
    }

    @Override
    public Dao<Routine, Long> getConcreteDao() {
        try {
            return dbHelper.getRoutinesDao();
        } catch (SQLException e) {
            throw new RuntimeException("Error creating routines dao", e);
        }
    }


    @Override
    public void fireEvent() {
        CalendulaApp.eventBus().post(PersistenceEvents.ROUTINE_EVENT);
    }

    @Override
    public List<Routine> findAll() {
        try {
            return dao.queryBuilder().orderBy(Routine.COLUMN_TIME, true).query();
        } catch (SQLException e) {
            throw new RuntimeException("Error finding models", e);
        }
    }


    public List<Routine> findAllForActivePatient(Context ctx) {
        return findAll(DB.patients().getActive(ctx));
    }

    public List<Routine> findAllWithNameForActivePatient(Context ctx) {
        Patient patient = DB.patients().getActive(ctx);
        return patient == null ? Collections.<Routine>emptyList()
                : findAllWithName(patient.getId());
    }

    public List<Routine> findAll(Patient p) {
        // No active owner means no patient data; never query NULL-owned rows.
        return p == null || p.getId() == null
                ? Collections.<Routine>emptyList() : findAll(p.getId());
    }


    public List<Routine> findAll(Long patientId) {
        if (patientId == null) {
            return Collections.emptyList();
        }
        try {
            return dao.queryBuilder()
                    .orderBy(Routine.COLUMN_TIME, true)
                    .where().eq(Routine.COLUMN_PATIENT, patientId)
                    .query();
        } catch (SQLException e) {
            throw new RuntimeException("Error finding models", e);
        }
    }

    public List<Routine> findAllWithName(Long patientId) {
        if (patientId == null) {
            return Collections.emptyList();
        }
        try {
            return dao.queryBuilder()
                    .orderBy(Routine.COLUMN_TIME, true)
                    .where().eq(Routine.COLUMN_PATIENT, patientId)
                    .and().isNotNull(Routine.COLUMN_NAME)
                    .query();
        } catch (SQLException e) {
            throw new RuntimeException("Error finding models", e);
        }
    }

    /**
     * Only the affected patient's autogenerated, unnamed routines can be
     * pruned during a schedule edit. Never perform a global cleanup from
     * a patient-scoped action.
     */
    public List<Routine> findWithoutName(Patient patient) {
        if (patient == null || patient.getId() == null || patient.getId() <= 0L) {
            return Collections.emptyList();
        }
        try {
            QueryBuilder<Routine, Long> qb = dao.queryBuilder();
            Where<Routine, Long> where = qb.where();
            where.and(where.eq(Routine.COLUMN_PATIENT, patient.getId()),
                    where.isNull(Routine.COLUMN_NAME));
            qb.setWhere(where);
            return qb.query();
        } catch (SQLException e) {
            throw new RuntimeException("Error finding patient-scoped unnamed routines", e);
        }
    }

    public Routine findByPatientAndName(String name, Patient p) {
        // Never match null-owned routines when the active patient is missing.
        if (p == null || p.getId() == null) {
            return null;
        }
        try {
            QueryBuilder<Routine, Long> qb = dao.queryBuilder();
            Where w = qb.where();
            w.and(w.eq(Routine.COLUMN_NAME, name), w.eq(Routine.COLUMN_PATIENT, p));
            qb.setWhere(w);
            return qb.queryForFirst();
        } catch (SQLException e) {
            throw new RuntimeException("Error finding routine", e);
        }
    }

    public Routine findByPatientAndDailyEvent(Patient patient, RepeatType dailyEvent) {
        if (patient == null || patient.getId() == null) {
            return null;
        }
        try {
            QueryBuilder<Routine, Long> qb = dao.queryBuilder();
            Where w = qb.where();
            w.and(w.eq(Routine.COLUMN_PATIENT, patient), w.eq(Routine.COLUMN_DAILY_EVENT, dailyEvent));
            qb.setWhere(w);
            return qb.queryForFirst();
        } catch (SQLException e) {
            throw new RuntimeException("Error finding routine", e);
        }
    }

    public Routine findByPatientAndTime(Patient p, LocalTime time) {
        // A null timestamp is not a valid patient routine lookup either.
        if (p == null || p.getId() == null || time == null) {
            return null;
        }
        try {
            QueryBuilder<Routine, Long> qb = dao.queryBuilder();
            Where w = qb.where();
            w.and(w.eq(Routine.COLUMN_TIME, time), w.eq(Routine.COLUMN_PATIENT, p));
            qb.setWhere(w);
            return qb.queryForFirst();
        } catch (SQLException e) {
            throw new RuntimeException("Error finding routine", e);
        }
    }


    public List<Routine> findInHour(int hour) {
        try {
            LocalTime time = new LocalTime(hour, 0);

            LocalTime endTime = time.plusMinutes(59);

            return queryBuilder().where()
                    .between(Routine.COLUMN_TIME, time, endTime)
                    .query();
        } catch (Exception e) {
            LogUtil.e(TAG, "Routine lookup failed");
            throw new RuntimeException(e);
        }
    }

    public void deleteCascade(final Routine r, boolean fireEvent) {

        // TODO: 6/27/17 delete schedules bound to this routine

        DB.transaction(new Callable<Object>() {
            @Override
            public Object call() throws Exception {

                DB.routines().remove(r);
                return null;
            }
        });

        if (fireEvent) {
            fireEvent();
        }
    }
}
